"""Turn analysis/results.json into LaTeX macros + tables for the manuscript.

    python make_tables.py ../../source_code/extension/analysis/results.json

Writes generated/results.tex. Without a results file, it writes "??" placeholders,
so the manuscript always compiles.
"""
import json, shutil, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated" / "results.tex"

DATASETS = [("coqa", "Coqa", "CoQA"), ("triviaqa", "Tqa", "TriviaQA"), ("nq", "Nq", "NQ-Open")]
METHODS = [  # (key in results.json, macro suffix, table label, show in table)
    ("Perplexity", "Ppl", "Perplexity", True),
    ("LN-Entropy", "Lne", "LN-Entropy", True),
    ("Lexical Similarity", "Lex", "Lexical Similarity", True),
    ("EigenScore", "Es", "EigenScore (layer 16)", True),
    ("M1 MLES", "Mles", r"\textbf{M1}: Multi-layer ES", True),
    ("M2a L2 (single)", "Mtwoas", "M2a: L2-norm, single", False),
    ("M2a L2 (multi)", "Mtwoam", r"\textbf{M2a}: L2-norm, multi", True),
    ("M2b std (single)", "Mtwobs", "M2b: standardised, single", False),
    ("M2b std (multi)", "Mtwobm", r"\textbf{M2b}: standardised, multi", True),
    ("M3 HYB (MLES+LNE)", "Hyb", r"\textbf{M3}: Hybrid (M1 + LNE)", True),
    ("M3b MLES+PPL", "Hybppl", "M3b: M1 + Perplexity", False),
    ("X1 XDS (cross-depth instability)", "Xds", r"\textbf{XDS} (cross-depth)", True),
    ("X2 depth slope", "Slope", "Depth slope", False),
    ("X3 MLES+XDS", "Mlesxds", r"\textbf{M1 + XDS}", True),
]
TESTS = [  # (key in results.json tests, macro suffix, table label)
    ("M1 MLES", "Mles", r"M1 vs ES (\emph{primary})"),
    ("M2a L2 (multi)", "Mtwoam", "M2a (multi) vs ES"),
    ("M2b std (multi)", "Mtwobm", "M2b (multi) vs ES"),
    ("M3 HYB (MLES+LNE)", "Hyb", "M3 vs ES"),
    ("X1 XDS (cross-depth instability)", "Xds", "XDS vs ES"),
    ("X3 MLES+XDS", "Mlesxds", "M1+XDS vs ES"),
    ("X3 MLES+XDS vs M1 MLES", "MlesxdsVsMles", "M1+XDS vs M1"),
    ("M3 HYB vs M1 MLES", "HybVsMles", "M3 vs M1"),
]
PH = r"\textbf{??}"


def pct(x, signed=False):
    if x is None or x != x:
        return "--"
    return f"{100 * x:+.1f}" if signed else f"{100 * x:.1f}"


def main(path):
    R = json.loads(Path(path).read_text()) if path and Path(path).exists() else None
    get = (lambda ds: next((v for k, v in R.items() if k.endswith(ds)), None)) if R else (lambda ds: None)
    L = ["% auto-generated by make_tables.py -- do not edit by hand"]
    mac = lambda name, val: L.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    for key, D, _ in DATASETS:
        r = get(key)
        mac(f"n{D}", r["n"] if r else PH)
        mac(f"acc{D}", f"{100 * r['accuracy']:.1f}" if r else PH)
        mac(f"best{D}", r["best_layer"]["index"] if r else PH)
        mac(f"bestauc{D}", pct(r["best_layer"]["auroc"]) if r else PH)
        mac(f"rho{D}", f"{r['xds_overlap']['spearman_MLES_XDS']:.2f}" if r else PH)
        mac(f"scn{D}", r["self_consistent"]["n"] if r else PH)
        mac(f"ninc{D}", r["self_consistent"]["n_incorrect"] if r else PH)
        for mk, M, _, _ in METHODS:
            mac(f"auc{D}{M}", pct(r["auroc"][mk]) if r else PH)
            mac(f"sc{D}{M}", pct(r["self_consistent"]["flag_rate_at_20fpr"][mk]) if r else PH)
        for tk, T, _ in TESTS:
            t = r["tests"][tk] if r else None
            mac(f"d{D}{T}", pct(t["delta"], True) if t else PH)
            mac(f"ci{D}{T}", f"[{pct(t['lo'], True)}, {pct(t['hi'], True)}]" if t else PH)
            mac(f"p{D}{T}", f"{t['p_pos']:.2f}" if t else PH)

    # Table I: AUROC
    L += [r"\newcommand{\tableAUROC}{%", r"\begin{table}[t]", r"\centering",
          r"\caption{AUROC (\%) on 1{,}000 questions per dataset (Llama-2-7B, 4-bit). "
          r"Label: greedy answer ROUGE-L $\le 0.5$. Bold rows are proposed methods.}",
          r"\label{tab:auroc}", r"\small", r"\setlength{\tabcolsep}{4pt}",
          r"\begin{tabular}{@{}lccc@{}}", r"\hline",
          r"Method & CoQA & TriviaQA & NQ-Open \\", r"\hline"]
    for mk, M, label, show in METHODS:
        if show:
            L.append(f"{label} & " + " & ".join(f"\\auc{D}{M}" for _, D, _ in DATASETS) + r" \\")
            if mk == "EigenScore":
                L.append(r"\hline")
    L += [r"\hline", r"\end{tabular}", r"\end{table}}"]

    # Table II: paired bootstrap
    L += [r"\newcommand{\tableBoot}{%", r"\begin{table*}[t]", r"\centering",
          r"\caption{Paired bootstrap over questions (10{,}000 resamples): $\Delta$AUROC in points, "
          r"95\% CI, and $P(\Delta>0)$. Only M1 vs EigenScore is the pre-registered primary test.}",
          r"\label{tab:boot}", r"\small",
          r"\begin{tabular}{@{}lccc@{}}", r"\hline",
          r"Comparison & CoQA & TriviaQA & NQ-Open \\", r"\hline"]
    for tk, T, label in TESTS:
        L.append(f"{label} & " + " & ".join(
            f"\\d{D}{T}\\ \\ci{D}{T}, $p$=\\p{D}{T}" for _, D, _ in DATASETS) + r" \\")
    L += [r"\hline", r"\end{tabular}", r"\end{table*}}"]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    fig = Path(path).parent / "per_layer_auroc.png" if path else None
    if fig and fig.exists():
        shutil.copy(fig, HERE / "figures" / "per_layer_auroc.png")
    print(f"wrote {OUT} ({'results' if R else 'placeholders'})")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
